function decodeXml(value: string): string {
  return value
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'");
}

function tagValue(xml: string, tag: string): string {
  const match = xml.match(new RegExp(`<${tag}[^>]*>(?:<!\\[CDATA\\[)?([\\s\\S]*?)(?:\\]\\]>)?</${tag}>`));
  return decodeXml((match?.[1] ?? "").trim());
}

export function parseAtomFeed(xml: string): Video[] {
  const channelName = tagValue(xml, "title");
  return [...xml.matchAll(/<entry>([\s\S]*?)<\/entry>/g)].map((match) => {
    const entry = match[1];
    const videoId = tagValue(entry, "yt:videoId");
    return {
      videoId,
      title: tagValue(entry, "title"),
      url: `https://www.youtube.com/watch?v=${videoId}`,
      published: tagValue(entry, "published"),
      thumbnailUrl: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
      channelName,
    };
  }).filter((video) => video.videoId.length > 0);
}

export function extractChannelId(input: string, pageHtml = ""): string | null {
  const direct = input.match(/(?:channel\/)?(UC[A-Za-z0-9_-]{22})/);
  if (direct) return direct[1];
  const patterns = [
    /"channelId"\s*:\s*"(UC[A-Za-z0-9_-]{22})"/,
    /"externalId"\s*:\s*"(UC[A-Za-z0-9_-]{22})"/,
    /youtube\.com\/channel\/(UC[A-Za-z0-9_-]{22})/,
  ];
  for (const pattern of patterns) {
    const match = pageHtml.match(pattern);
    if (match) return match[1];
  }
  return null;
}

export function normalizeYouTubeInput(input: string): string {
  const value = input.trim().replace(/^<|>$/g, "");
  if (/^UC[A-Za-z0-9_-]{22}$/.test(value)) return value;
  const candidate = value.startsWith("@")
    ? `https://www.youtube.com/${value}`
    : /^[A-Za-z0-9.-]+\//.test(value)
      ? `https://${value}`
      : value;
  let url: URL;
  try {
    url = new URL(candidate);
  } catch {
    throw new Error("Use a YouTube channel ID, @handle, channel URL, or video URL.");
  }
  const host = url.hostname.toLowerCase().replace(/^www\./, "");
  if (host !== "youtube.com" && host !== "m.youtube.com" && host !== "youtu.be") {
    throw new Error("Only YouTube channel and video addresses are supported.");
  }
  return url.toString();
}

export function extractVideoId(input: string): string | null {
  const direct = input.trim().match(/^[A-Za-z0-9_-]{11}$/);
  if (direct) return direct[0];
  try {
    const url = new URL(normalizeYouTubeInput(input));
    if (url.hostname.toLowerCase().replace(/^www\./, "") === "youtu.be") {
      return url.pathname.split("/").filter(Boolean)[0]?.match(/^[A-Za-z0-9_-]{11}$/)?.[0] ?? null;
    }
    const pathMatch = url.pathname.match(/^\/(?:shorts|live|embed)\/([A-Za-z0-9_-]{11})/);
    return url.searchParams.get("v")?.match(/^[A-Za-z0-9_-]{11}$/)?.[0] ?? pathMatch?.[1] ?? null;
  } catch {
    return null;
  }
}

export function extractVideoIdsFromText(input: string): string[] {
  const ids: string[] = [];
  const candidates = input.match(/(?:https?:\/\/)?(?:www\.|m\.)?(?:youtube\.com\/[^\s<>]+|youtu\.be\/[^\s<>]+)/gi) ?? [];
  for (const candidate of candidates) {
    const videoId = extractVideoId(candidate.replace(/[),.;!?]+$/, ""));
    if (videoId && !ids.includes(videoId)) ids.push(videoId);
  }
  return ids;
}

/** Watch Better's balanced ytInitialPlayerResponse extraction, usable in Workers. */
export function extractYouTubePlayerResponse(source: string): Record<string, unknown> | null {
  const keyIndex = source.indexOf("ytInitialPlayerResponse");
  if (keyIndex < 0) return null;
  const start = source.indexOf("{", keyIndex);
  if (start < 0) return null;
  let depth = 0;
  let quoted = false;
  let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const character = source[index];
    if (quoted) {
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === '"') quoted = false;
      continue;
    }
    if (character === '"') quoted = true;
    else if (character === "{") depth += 1;
    else if (character === "}" && --depth === 0) {
      try {
        const value: unknown = JSON.parse(source.slice(start, index + 1));
        return value && typeof value === "object" && !Array.isArray(value)
          ? value as Record<string, unknown>
          : null;
      } catch {
        return null;
      }
    }
  }
  return null;
}

function recordValue(value: unknown, ...keys: string[]): Record<string, unknown> | null {
  let current: unknown = value;
  for (const key of keys) {
    if (!current || typeof current !== "object" || Array.isArray(current)) return null;
    current = (current as Record<string, unknown>)[key];
  }
  return current && typeof current === "object" && !Array.isArray(current)
    ? current as Record<string, unknown>
    : null;
}

function cleanCaptionText(value: string): string {
  return decodeXml(value).replaceAll("&#39;", "'").replace(/\u200b/g, "").replace(/\s+/g, " ").trim();
}

function mergeCaptionCues(cues: RawCaptionCue[]): RawCaptionCue[] {
  const output: RawCaptionCue[] = [];
  for (const cue of [...cues].sort((left, right) => left.startSeconds - right.startSeconds)) {
    if (!cue.text || cue.startSeconds < 0 || cue.endSeconds <= cue.startSeconds) continue;
    const previous = output.at(-1);
    if (previous && cue.text === previous.text && Math.abs(cue.startSeconds - previous.startSeconds) < 0.1) continue;
    const separated = previous && cue.startSeconds - previous.endSeconds > 1.5;
    if (previous && !separated && previous.text.length + cue.text.length < 180
      && previous.endSeconds - previous.startSeconds < 8 && !/[.!?…]["')\]]?$/.test(previous.text)) {
      previous.endSeconds = Math.max(previous.endSeconds, cue.endSeconds);
      previous.text = cleanCaptionText(`${previous.text} ${cue.text}`);
    } else {
      output.push({ ...cue });
    }
  }
  return output;
}

export function parseJson3CaptionCues(payload: unknown): RawCaptionCue[] {
  if (!payload || typeof payload !== "object" || !Array.isArray((payload as Record<string, unknown>).events)) return [];
  const cues: RawCaptionCue[] = [];
  for (const event of (payload as { events: unknown[] }).events) {
    if (!event || typeof event !== "object") continue;
    const item = event as Record<string, unknown>;
    if (!Array.isArray(item.segs)) continue;
    const startMs = Number(item.tStartMs);
    const durationMs = Number(item.dDurationMs);
    if (!Number.isFinite(startMs) || !Number.isFinite(durationMs)) continue;
    const text = cleanCaptionText(item.segs.map((segment) => {
      if (!segment || typeof segment !== "object") return "";
      const value = (segment as Record<string, unknown>).utf8;
      return typeof value === "string" ? value : "";
    }).join(""));
    if (text && text !== "\n") cues.push({
      startSeconds: startMs / 1000,
      endSeconds: (startMs + Math.max(1, durationMs)) / 1000,
      text,
    });
  }
  return mergeCaptionCues(cues);
}

function srtTimestamp(seconds: number): string {
  const milliseconds = Math.max(0, Math.round(seconds * 1000));
  const hours = Math.floor(milliseconds / 3_600_000);
  const minutes = Math.floor((milliseconds % 3_600_000) / 60_000);
  const remainder = Math.floor((milliseconds % 60_000) / 1000);
  const millis = milliseconds % 1000;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}:${String(remainder).padStart(2, "0")},${String(millis).padStart(3, "0")}`;
}

function cuesToSrt(cues: RawCaptionCue[]): string {
  return cues.map((cue, index) => `${index + 1}\n${srtTimestamp(cue.startSeconds)} --> ${srtTimestamp(cue.endSeconds)}\n${cue.text}`).join("\n\n");
}

