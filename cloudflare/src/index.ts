export async function saveCaptionUpload(
  request: Request,
  env: Env,
  includeResearchTables = true,
): Promise<Response> {
  const contentLength = Number(request.headers.get("content-length") || 0);
  if (contentLength > MAX_CACHED_CAPTION_BYTES + 100_000) {
    return new Response("Caption payload too large", { status: 413 });
  }
  const body = await request.text();
  const ingestSecret = env.CAPTION_INGEST_SECRET || env.DISCORD_TOKEN;
  if (!(await validCaptionCacheSignature(request, body, ingestSecret))) {
    return new Response("Invalid caption signature", { status: 401 });
  }
  let upload: unknown;
  try {
    upload = JSON.parse(body);
  } catch {
    return new Response("Invalid JSON", { status: 400 });
  }
  if (!isCaptionUpload(upload)) return new Response("Invalid caption payload", { status: 400 });
  const byteLength = new TextEncoder().encode(upload.plainText + upload.srtText).byteLength;
  if (byteLength > MAX_CACHED_CAPTION_BYTES) return new Response("Caption payload too large", { status: 413 });
  await ensureCaptionTable(env);
  const now = new Date().toISOString();
  if (!includeResearchTables) {
    await env.DB.prepare(
      `INSERT OR REPLACE INTO captions (video_id, language, plain_text, srt_text, fetched_at)
       VALUES (?, ?, ?, ?, ?)`,
    ).bind(upload.videoId, upload.language, upload.plainText, upload.srtText, now).run();
    return json({ ok: true, videoId: upload.videoId, segments: parseSrtSegments(upload.srtText).length });
  }
  const provider = (upload.provider || "youtube-player").slice(0, 100);
  const sourceType = (upload.sourceType || "youtube_captions").slice(0, 100);
  const segments = parseSrtSegments(upload.srtText);
  await ensureVideoRow(env, upload.videoId, {
    title: upload.title?.trim().slice(0, 256) || `YouTube video ${upload.videoId}`,
    channelName: upload.channelName?.trim().slice(0, 256) || "Unknown channel",
    url: `https://www.youtube.com/watch?v=${upload.videoId}`,
  });
  const statements: D1PreparedStatement[] = [
    env.DB.prepare(
      `INSERT OR REPLACE INTO captions (video_id, language, plain_text, srt_text, fetched_at)
       VALUES (?, ?, ?, ?, ?)`,
    ).bind(upload.videoId, upload.language, upload.plainText, upload.srtText, now),
    env.DB.prepare(
      `INSERT INTO transcripts
       (video_id, language, provider, source_type, is_auto_generated, state, plain_text, srt_text, retrieved_at, created_at, updated_at)
       VALUES (?, ?, ?, ?, ?, 'ready', ?, ?, ?, ?, ?)
       ON CONFLICT(video_id, language) DO UPDATE SET provider = excluded.provider,
         source_type = excluded.source_type, is_auto_generated = excluded.is_auto_generated,
         state = 'ready', failure_reason = NULL, next_attempt_at = NULL,
         plain_text = excluded.plain_text, srt_text = excluded.srt_text,
         retrieved_at = excluded.retrieved_at, updated_at = excluded.updated_at`,
    ).bind(upload.videoId, upload.language, provider, sourceType, upload.isAutoGenerated ? 1 : 0,
      upload.plainText, upload.srtText, now, now, now),
    env.DB.prepare(
      "DELETE FROM transcript_segments WHERE video_id = ? AND language = ?",
    ).bind(upload.videoId, upload.language),
    env.DB.prepare(
      `UPDATE jobs SET status = 'completed', updated_at = ?, last_error = NULL
       WHERE job_key = ?`,
    ).bind(now, `transcript:${upload.videoId}`),
  ];
  for (const [batchIndex, chunk] of transcriptSegmentBatches(segments).entries()) {
    const offset = batchIndex * TRANSCRIPT_SEGMENT_BATCH_SIZE;
    const values = chunk.map(() => "(?, ?, ?, ?, ?, ?, ?, ?)").join(",");
    const parameters = chunk.flatMap((segment, index) => [
      upload.videoId,
      upload.language,
      offset + index,
      segment.startSeconds,
      segment.durationSeconds,
      segment.text,
      provider,
      now,
    ]);
    statements.push(env.DB.prepare(
      `INSERT INTO transcript_segments
       (video_id, language, segment_index, start_seconds, duration_seconds, text, provider, retrieved_at)
       VALUES ${values}`,
    ).bind(...parameters));
  }
  await env.DB.batch(statements);
  logEvent("info", "transcript_ready", {
    video_id: upload.videoId,
    provider,
    segments: segments.length,
  });
  return json({ ok: true, videoId: upload.videoId, segments: segments.length });
}

