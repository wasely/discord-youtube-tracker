async function discoverTranscriptRequests(env: Env, channelId: string): Promise<void> {
  const messages = await (await discordApi(env, `/channels/${channelId}/messages?limit=25`)).json() as DiscordMessage[];
  const botReplies = new Set(messages.flatMap((message) =>
    message.author?.bot && message.message_reference?.message_id
      ? [message.message_reference.message_id]
      : []));
  const now = new Date().toISOString();
  const statements: D1PreparedStatement[] = [];
  for (const message of messages) {
    if (message.author?.bot || botReplies.has(message.id)) continue;
    for (const videoId of extractVideoIdsFromText(message.content || "").slice(0, 3)) {
      statements.push(env.DB.prepare(
        `INSERT OR IGNORE INTO transcript_intake_requests
         (message_id, channel_id, video_id, status, created_at, updated_at)
         VALUES (?, ?, ?, 'queued', ?, ?)`,
      ).bind(message.id, channelId, videoId, now, now));
    }
  }
  if (statements.length) await env.DB.batch(statements);
}

async function processTranscriptRequest(env: Env, request: TranscriptIntakeRequest): Promise<void> {
  const now = new Date().toISOString();
  const claim = await env.DB.prepare(
    `UPDATE transcript_intake_requests SET status = 'running', attempts = attempts + 1, updated_at = ?
     WHERE message_id = ? AND video_id = ? AND status IN ('queued', 'retrying')`,
  ).bind(now, request.message_id, request.video_id).run();
  if (!claim.meta.changes) return;
  try {
    const captions = await getCaptions(env, request.video_id);
    const metadata = {
      title: captions.title || `YouTube video ${request.video_id}`,
      channelName: captions.channelName || "Unknown channel",
      url: `https://www.youtube.com/watch?v=${request.video_id}`,
    };
    const origin = env.PUBLIC_TRANSCRIPT_ORIGIN?.trim();
    if (origin) {
      const preview = transcriptPreview(captions);
      await discordApi(env, `/channels/${request.channel_id}/messages`, {
        method: "POST",
        body: JSON.stringify({
          content: `${preview}\n\nOpen the full plain-text transcript below to copy it in one tap.`.slice(0, 1_950),
          components: videoActionComponents(request.video_id, origin),
          message_reference: { message_id: request.message_id, fail_if_not_exists: false },
          allowed_mentions: { parse: [] },
        }),
      });
    } else {
      await discordApi(env, `/channels/${request.channel_id}/messages`, {
        method: "POST",
        body: multipartMessage({
          content: `**${metadata.title.replaceAll("@", "").slice(0, 200)}** — complete transcript ready.`,
          message_reference: { message_id: request.message_id, fail_if_not_exists: false },
          allowed_mentions: { parse: [] },
        }, captionFiles(captions, metadata)),
      });
    }
    await env.DB.prepare(
      `UPDATE transcript_intake_requests SET status = 'completed', next_attempt_at = NULL,
       last_error = NULL, updated_at = ? WHERE message_id = ? AND video_id = ?`,
    ).bind(new Date().toISOString(), request.message_id, request.video_id).run();
  } catch (error) {
    const attempts = request.attempts + 1;
    const detail = (error instanceof Error ? error.message : String(error)).slice(0, 500);
    const dead = attempts >= 3;
    await env.DB.prepare(
      `UPDATE transcript_intake_requests SET status = ?, next_attempt_at = ?, last_error = ?, updated_at = ?
       WHERE message_id = ? AND video_id = ?`,
    ).bind(
      dead ? "failed" : "retrying",
      dead ? null : new Date(Date.now() + retryDelaySeconds(attempts) * 1000).toISOString(),
      detail,
      new Date().toISOString(),
      request.message_id,
      request.video_id,
    ).run();
    if (dead) {
      await discordApi(env, `/channels/${request.channel_id}/messages`, {
        method: "POST",
        body: JSON.stringify({
          content: `Could not get this transcript after retries. ${detail}`.slice(0, 1900),
          message_reference: { message_id: request.message_id, fail_if_not_exists: false },
          allowed_mentions: { parse: [] },
        }),
      });
    }
  }
}

export async function runTranscriptIntake(env: Env): Promise<number> {
  await ensureTranscriptIntakeTable(env);
  await env.DB.prepare(
    `UPDATE transcript_intake_requests
     SET status = 'queued', attempts = 0, next_attempt_at = NULL, last_error = NULL, updated_at = ?
     WHERE status = 'failed' AND EXISTS (
       SELECT 1 FROM captions WHERE captions.video_id = transcript_intake_requests.video_id
     )`,
  ).bind(new Date().toISOString()).run();
  let guilds: Array<{ id: string }> = [];
  try {
    guilds = await (await discordApi(env, "/users/@me/guilds?limit=200")).json() as Array<{ id: string }>;
  } catch (error) {
    logEvent("warn", "guild_discovery_failed", { error: error instanceof Error ? error.message : String(error) });
  }
  if (!guilds.length) {
    const rows = await env.DB.prepare(
      "SELECT DISTINCT guild_id AS id FROM routes WHERE guild_id IS NOT NULL",
    ).all<{ id: string }>();
    guilds = rows.results;
  }
  if (!guilds.length) {
    const routes = await env.DB.prepare(
      "SELECT DISTINCT discord_channel_id FROM routes",
    ).all<{ discord_channel_id: string }>();
    const discovered = new Set<string>();
    for (const route of routes.results) {
      try {
        const channel = await (await discordApi(env, `/channels/${route.discord_channel_id}`)).json() as { guild_id?: string };
        if (channel.guild_id) discovered.add(channel.guild_id);
      } catch {
        // A deleted or inaccessible legacy route must not block other guilds.
      }
    }
    guilds = [...discovered].map((id) => ({ id }));
  }
  for (const guild of guilds) {
    try {
      const channelId = await ensureTranscriptChannel(env, guild.id);
      await discoverTranscriptRequests(env, channelId);
    } catch (error) {
      logEvent("warn", "transcript_channel_scan_failed", {
        guild_id: guild.id,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }
  const due = await env.DB.prepare(
    `SELECT message_id, channel_id, video_id, attempts FROM transcript_intake_requests
     WHERE status IN ('queued', 'retrying') AND (next_attempt_at IS NULL OR next_attempt_at <= ?)
     ORDER BY created_at LIMIT 4`,
  ).bind(new Date().toISOString()).all<TranscriptIntakeRequest>();
  await Promise.all(due.results.map((request) => processTranscriptRequest(env, request)));
  return due.results.length;
}

