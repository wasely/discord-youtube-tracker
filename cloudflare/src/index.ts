async function handleInteraction(env: Env, interaction: DiscordInteraction): Promise<void> {
  try {
    const command = interaction.data?.name;
    const option = (name: string) => interaction.data?.options?.find((item) => item.name === name)?.value ?? "";
    const input = option("channel");
    const canManage = (BigInt(interaction.member?.permissions ?? "0") & MANAGE_GUILD) !== 0n;
    let message: string;
    if (["addchannel", "removechannel", "checkchannels", "health"].includes(command || "")) {
      if (!canManage) throw new Error("You need Manage Server permission for this command.");
    }
    if (command === "addchannel") message = await addChannel(env, interaction, input);
    else if (command === "removechannel") message = await removeChannel(env, interaction, input);
    else if (command === "channels") message = await listChannels(env, interaction);
    else if (command === "transcript") message = await transcriptResponse(env, option("video"), option("query"));
    else if (command === "health") message = await healthSummary(env);
    else if (command === "checkchannels") {
      const posted = await runPoll(env);
      message = `Check complete. Posted ${posted} new video(s).`;
    } else message = "Unknown tracker command.";
    await editInteraction(env, interaction, message.slice(0, 1900));
  } catch (error) {
    await editInteraction(env, interaction, `Tracker error: ${error instanceof Error ? error.message : String(error)}`.slice(0, 1900));
  }
}

function newVideos(videos: Video[], lastVideoId: string | null): Video[] {
  if (!lastVideoId) return [];
  const pending: Video[] = [];
  for (const video of videos) {
    if (video.videoId === lastVideoId) break;
    pending.push(video);
  }
  return pending.reverse();
}

async function queueVideos(env: Env, routes: Route[], videosByChannel: Map<string, Video[]>): Promise<void> {
  const inserts: Array<{ route: Route; video: Video }> = [];
  const updates: Array<{ channelId: string; latest: string }> = [];
  for (const [channelId, videos] of videosByChannel) {
    if (!videos.length) continue;
    const channelRoutes = routes.filter((route) => route.youtube_channel_id === channelId && route.enabled !== 0);
    for (const route of channelRoutes) {
      for (const video of newVideos(videos, route.last_video_id)) inserts.push({ route, video });
    }
    updates.push({ channelId, latest: videos[0].videoId });
  }

  const now = new Date().toISOString();
  const statements: D1PreparedStatement[] = [];
  const uniqueVideos = [...new Map(inserts.map(({ route, video }) => [
    video.videoId,
    { video, channelId: route.youtube_channel_id },
  ])).values()];
  for (const { video, channelId } of uniqueVideos) {
    statements.push(env.DB.prepare(
      `INSERT INTO videos
       (video_id, youtube_channel_id, youtube_channel_name, title, url, published, thumbnail_url, first_seen_at, updated_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
       ON CONFLICT(video_id) DO UPDATE SET title = excluded.title, url = excluded.url,
         thumbnail_url = excluded.thumbnail_url, updated_at = excluded.updated_at`,
    ).bind(video.videoId, channelId, video.channelName, video.title, video.url, video.published, video.thumbnailUrl, now, now));
    statements.push(env.DB.prepare(
      `INSERT OR IGNORE INTO jobs
       (job_key, type, entity_id, status, scheduled_at, created_at, updated_at)
       VALUES (?, 'transcript', ?, 'queued', ?, ?, ?)`,
    ).bind(`transcript:${video.videoId}`, video.videoId, now, now, now));
  }
  for (const { route, video } of inserts) {
    statements.push(env.DB.prepare(
      `INSERT OR IGNORE INTO notifications
       (guild_id, discord_channel_id, video_id, state, discovered_at, updated_at)
       VALUES (?, ?, ?, 'discovered', ?, ?)`,
    ).bind(route.guild_id || `legacy:${route.discord_channel_id}`, route.discord_channel_id, video.videoId, now, now));
  }
  for (let index = 0; index < inserts.length; index += 10) {
    const chunk = inserts.slice(index, index + 10);
    const values = chunk.map(() => "(?, ?, ?, ?, ?, ?, ?, ?)").join(",");
    const parameters = chunk.flatMap(({ route, video }) => [
      route.discord_channel_id,
      route.youtube_channel_id,
      route.youtube_channel_name,
      video.videoId,
      video.title,
      video.url,
      video.published,
      video.thumbnailUrl,
    ]);
    statements.push(env.DB.prepare(
      `INSERT OR IGNORE INTO pending_posts
       (discord_channel_id, youtube_channel_id, youtube_channel_name, video_id, title, url, published, thumbnail_url)
       VALUES ${values}`,
    ).bind(...parameters));
  }
  if (inserts.length) {
    statements.push(env.DB.prepare(
      `DELETE FROM pending_posts
       WHERE EXISTS (
         SELECT 1 FROM notifications n
         WHERE n.discord_channel_id = pending_posts.discord_channel_id
           AND n.video_id = pending_posts.video_id
           AND n.state = 'notification_sent'
       )`,
    ));
  }
  if (updates.length) {
    const cases = updates.map(() => "WHEN ? THEN ?").join(" ");
    const ids = updates.map(() => "?").join(",");
    statements.push(env.DB.prepare(
      `UPDATE routes
       SET last_video_id = CASE youtube_channel_id ${cases} ELSE last_video_id END,
           last_checked_at = ?
       WHERE enabled = 1 AND youtube_channel_id IN (${ids})`,
    ).bind(
      ...updates.flatMap(({ channelId, latest }) => [channelId, latest]),
      now,
      ...updates.map(({ channelId }) => channelId),
    ));
  }
  statements.push(env.DB.prepare(
    `INSERT INTO health_state (key, value, updated_at) VALUES ('last_successful_upload_check', ?, ?)
     ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
  ).bind(now, now));
  if (statements.length) await env.DB.batch(statements);
  for (const { route, video } of inserts) {
    logEvent("info", "upload_detected", {
      video_id: video.videoId,
      guild_id: route.guild_id,
      discord_channel_id: route.discord_channel_id,
    });
  }
}

async function sendPending(env: Env): Promise<number> {
  const now = new Date().toISOString();
  const pending = await env.DB.prepare(
    `SELECT * FROM pending_posts
     WHERE dead_at IS NULL AND attempts < ?
       AND (next_attempt_at IS NULL OR next_attempt_at <= ?)
     ORDER BY id LIMIT ?`,
  ).bind(MAX_SEND_ATTEMPTS, now, SEND_BATCH_SIZE).all<Record<string, string | number | null>>();
  let sent = 0;
  for (const post of pending.results) {
    const videoId = String(post.video_id);
    const channelId = String(post.discord_channel_id);
    try {
      let captionsReady = false;
      try {
        await getCaptions(env, videoId);
        captionsReady = true;
      } catch {
        // Transcript work is independent and must never block the upload card.
      }
      await env.DB.prepare(
        `UPDATE notifications SET state = 'sending', attempts = attempts + 1, updated_at = ?
         WHERE discord_channel_id = ? AND video_id = ?`,
      ).bind(now, channelId, videoId).run();
      const payload = {
        nonce: String(post.id),
        enforce_nonce: true,
        embeds: [{
          title: String(post.title).slice(0, 256),
          url: post.url,
          description: captionsReady
            ? "Transcript ready • Open the private Transcript action to search or download."
            : "Transcript queued • The upload is available now while research processing continues.",
          color: 0xff0000,
          timestamp: post.published || undefined,
          author: { name: post.youtube_channel_name, url: `https://youtube.com/channel/${post.youtube_channel_id}` },
          image: { url: post.thumbnail_url },
          fields: [
            { name: "Type", value: "Video", inline: true },
            { name: "Transcript", value: captionsReady ? "Ready" : "Processing", inline: true },
          ],
          footer: { text: `${PRODUCT_NAME} • Research feed` },
        }],
        components: videoActionComponents(videoId, publicOrigin(env, "")),
        allowed_mentions: { parse: [] },
      };
      const response = await discordApi(env, `/channels/${channelId}/messages`, {
        method: "POST",
        body: JSON.stringify(payload),
      });
      const message = await response.json() as { id?: string };
      const sentAt = new Date().toISOString();
      await env.DB.batch([
        env.DB.prepare(
          `UPDATE notifications
           SET state = 'notification_sent', discord_message_id = ?, sent_at = ?, updated_at = ?, last_error = NULL
           WHERE discord_channel_id = ? AND video_id = ?`,
        ).bind(message.id || null, sentAt, sentAt, channelId, videoId),
        env.DB.prepare("DELETE FROM pending_posts WHERE id = ?").bind(post.id),
      ]);
      logEvent("info", "notification_sent", {
        video_id: videoId,
        discord_channel_id: channelId,
        discord_message_id: message.id,
      });
      sent += 1;
    } catch (error) {
      const attempts = Number(post.attempts || 0) + 1;
      const detail = (error instanceof Error ? error.message : String(error)).slice(0, 500);
      const dead = attempts >= MAX_SEND_ATTEMPTS;
      const nextAttempt = new Date(Date.now() + retryDelaySeconds(attempts) * 1000).toISOString();
      await env.DB.batch([
        env.DB.prepare(
          `UPDATE pending_posts
           SET attempts = ?, next_attempt_at = ?, last_error = ?, dead_at = ?
           WHERE id = ?`,
        ).bind(attempts, dead ? null : nextAttempt, detail, dead ? new Date().toISOString() : null, post.id),
        env.DB.prepare(
          `UPDATE notifications SET state = 'failed', last_error = ?, updated_at = ?
           WHERE discord_channel_id = ? AND video_id = ?`,
        ).bind(detail, new Date().toISOString(), channelId, videoId),
      ]);
      logEvent(dead ? "error" : "warn", dead ? "job_permanently_failed" : "notification_retry", {
        video_id: videoId,
        discord_channel_id: channelId,
        attempts,
        next_attempt_at: dead ? null : nextAttempt,
        error: detail,
      });
    }
  }
  return sent;
}

async function feedCategoryChannels(env: Env): Promise<string[]> {
  const found: string[] = [];
  let guilds: Array<{ id: string }> = [];
  try {
    guilds = await (await discordApi(env, "/users/@me/guilds?limit=200")).json() as Array<{ id: string }>;
  } catch (error) {
    logEvent("warn", "guild_discovery_failed", { error: error instanceof Error ? error.message : String(error) });
    return found;
  }
  for (const guild of guilds) {
    try {
      const channels = await (await discordApi(env, `/guilds/${guild.id}/channels`)).json() as Array<Record<string, unknown>>;
      const categoryIds = new Set(channels
        .filter((channel) => channel.type === 4 && FEED_CATEGORY_NAMES.includes(String(channel.name).toLowerCase()))
        .map((channel) => String(channel.id)));
      for (const channel of channels) {
        if (channel.type === 0 && categoryIds.has(String(channel.parent_id))) found.push(String(channel.id));
      }
    } catch (error) {
      logEvent("warn", "feed_channel_discovery_failed", {
        guild_id: guild.id,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }
  return found;
}

