export function retryDelaySeconds(attempt: number): number {
  return Math.min(3600, 30 * (2 ** Math.max(0, attempt - 1)));
}

async function sleep(milliseconds: number): Promise<void> {
  await new Promise((resolve) => setTimeout(resolve, milliseconds));
}

async function fetchWithTimeout(
  url: string,
  init: RequestInit = {},
  timeoutMs = REQUEST_TIMEOUT_MS,
): Promise<Response> {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetch(url, { ...init, signal: controller.signal });
  } finally {
    clearTimeout(timeout);
  }
}

async function discordApi(env: Env, path: string, init: RequestInit = {}): Promise<Response> {
  const headers = new Headers(init.headers);
  headers.set("authorization", `Bot ${env.DISCORD_TOKEN}`);
  if (typeof init.body === "string" && !headers.has("content-type")) {
    headers.set("content-type", "application/json");
  }
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    const response = await fetchWithTimeout(`${DISCORD_API}${path}`, { ...init, headers });
    if (response.ok) return response;
    if (response.status === 429 || response.status >= 500) {
      const retryAfter = Number(response.headers.get("retry-after"));
      const delayMs = Number.isFinite(retryAfter)
        ? Math.min(5000, retryAfter * 1000)
        : Math.min(5000, retryDelaySeconds(attempt) * 1000);
      logEvent("warn", "api_rate_limited", { provider: "discord", status: response.status, attempt });
      if (attempt < 3) {
        await response.body?.cancel();
        await sleep(delayMs);
        continue;
      }
    }
    const detail = (await response.text()).slice(0, 300);
    throw new Error(`Discord API ${response.status}: ${detail}`);
  }
  throw new Error("Discord API retry limit reached");
}

export async function editInteraction(
  env: Env,
  interaction: DiscordInteraction,
  content: string,
  components?: Array<Record<string, unknown>>,
): Promise<void> {
  const url = `${DISCORD_API}/webhooks/${interaction.application_id}/${interaction.token}/messages/@original`;
  const body = JSON.stringify({ content, components, allowed_mentions: { parse: [] } });
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    let response: Response;
    try {
      response = await fetchWithTimeout(url, {
        method: "PATCH",
        headers: { "content-type": "application/json" },
        body,
      });
    } catch (error) {
      if (attempt >= 3) throw error;
      await sleep(250 * attempt);
      continue;
    }
    if (response.ok) return;
    if ((response.status === 429 || response.status >= 500) && attempt < 3) {
      const retryAfter = Number(response.headers.get("retry-after"));
      await response.body?.cancel();
      await sleep(Number.isFinite(retryAfter) ? Math.min(5_000, retryAfter * 1_000) : 250 * attempt);
      continue;
    }
    const detail = (await response.text()).slice(0, 300);
    throw new Error(`Discord interaction update returned ${response.status}: ${detail}`);
  }
}

