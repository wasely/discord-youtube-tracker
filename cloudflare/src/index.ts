function captionTracks(player: Record<string, unknown>): YouTubeCaptionTrack[] {
  const renderer = recordValue(player, "captions", "playerCaptionsTracklistRenderer");
  const rawTracks = renderer?.captionTracks;
  if (!Array.isArray(rawTracks)) return [];
  const defaultIndex = Number(renderer?.defaultCaptionTrackIndex);
  return rawTracks.flatMap((value, index): Array<YouTubeCaptionTrack & { index: number }> => {
    if (!value || typeof value !== "object") return [];
    const track = value as Record<string, unknown>;
    if (typeof track.baseUrl !== "string") return [];
    return [{
      baseUrl: track.baseUrl,
      languageCode: typeof track.languageCode === "string" ? track.languageCode : undefined,
      kind: typeof track.kind === "string" ? track.kind : undefined,
      isDefault: track.isDefault === true || defaultIndex === index,
      index,
    }];
  }).sort((left, right) =>
    Number(!String(left.languageCode || "").toLowerCase().startsWith("en"))
      - Number(!String(right.languageCode || "").toLowerCase().startsWith("en"))
    || Number(left.kind === "asr") - Number(right.kind === "asr")
    || Number(!left.isDefault) - Number(!right.isDefault)
    || left.index - right.index);
}

async function loadCaptionTrack(player: Record<string, unknown>): Promise<CaptionBundle | null> {
  for (const track of captionTracks(player)) {
    const captionUrl = new URL(track.baseUrl);
    captionUrl.searchParams.set("fmt", "json3");
    try {
      const response = await fetchWithTimeout(captionUrl.toString(), {
        headers: { "user-agent": YOUTUBE_WATCH_USER_AGENT, "accept-language": "en-US,en;q=0.9" },
      });
      if (!response.ok) continue;
      const cues = parseJson3CaptionCues(JSON.parse(await response.text()));
      if (!cues.length) continue;
      const details = recordValue(player, "videoDetails");
      return {
        language: track.languageCode || "unknown",
        plainText: cues.map((cue) => cue.text).join("\n"),
        srtText: cuesToSrt(cues),
        title: typeof details?.title === "string" ? details.title : undefined,
        channelName: typeof details?.author === "string" ? details.author : undefined,
      };
    } catch (error) {
      logEvent("warn", "caption_track_failed", {
        language: track.languageCode,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }
  return null;
}

export async function fetchCaptionsFromYouTube(videoId: string): Promise<CaptionBundle> {
  let lastReason = "No readable caption track was returned.";

  // Same primary path as Watch Better: use YouTube's signed page caption URL.
  for (const pageUrl of [
    `https://www.youtube.com/watch?v=${videoId}`,
    `https://www.youtube.com/embed/${videoId}`,
  ]) {
    try {
      const pageResponse = await fetchWithTimeout(pageUrl, {
        headers: { "user-agent": YOUTUBE_WATCH_USER_AGENT, "accept-language": "en-US,en;q=0.9" },
      });
      if (pageResponse.ok) {
        const source = await pageResponse.text();
        const player = extractYouTubePlayerResponse(source);
        if (player) {
          const captions = await loadCaptionTrack(player);
          if (captions) return captions;
          const status = recordValue(player, "playabilityStatus");
          if (typeof status?.reason === "string") lastReason = status.reason;
        }
      } else {
        lastReason = `YouTube page returned ${pageResponse.status}.`;
      }
    } catch (error) {
      lastReason = error instanceof Error ? error.message : String(error);
    }
  }

  // Several official clients provide independent fallbacks when a cloud IP is challenged.
  const clients: Array<{ userAgent: string; client: Record<string, unknown> }> = [
    {
      userAgent: YOUTUBE_ANDROID_USER_AGENT,
      client: {
        clientName: "ANDROID",
        clientVersion: "20.10.38",
        androidSdkVersion: 30,
        userAgent: YOUTUBE_ANDROID_USER_AGENT,
        hl: "en",
        gl: "US",
      },
    },
    {
      userAgent: "com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 18_3_1 like Mac OS X;)",
      client: {
        clientName: "IOS",
        clientVersion: "20.10.4",
        deviceMake: "Apple",
        deviceModel: "iPhone16,2",
        osName: "iPhone",
        osVersion: "18.3.1.22D72",
        hl: "en",
        gl: "US",
      },
    },
    {
      userAgent: YOUTUBE_WATCH_USER_AGENT,
      client: {
        clientName: "WEB_EMBEDDED_PLAYER",
        clientVersion: "1.20250310.00.00",
        clientScreen: "EMBED",
        hl: "en",
        gl: "US",
      },
    },
  ];
  const playerResults = await Promise.allSettled(clients.map(async ({ userAgent, client }) => {
    const response = await fetchWithTimeout("https://www.youtube.com/youtubei/v1/player", {
      method: "POST",
      headers: { "content-type": "application/json", "user-agent": userAgent },
      body: JSON.stringify({
        videoId,
        context: { client },
        thirdParty: client.clientName === "WEB_EMBEDDED_PLAYER"
          ? { embedUrl: `https://www.youtube.com/embed/${videoId}` }
          : undefined,
      }),
    });
    if (!response.ok) throw new Error(`YouTube player returned ${response.status}.`);
    return response.json() as Promise<Record<string, unknown>>;
  }));
  for (const result of playerResults) {
    if (result.status === "rejected") {
      lastReason = result.reason instanceof Error ? result.reason.message : String(result.reason);
      continue;
    }
    try {
      const captions = await loadCaptionTrack(result.value);
      if (captions) return captions;
      const status = recordValue(result.value, "playabilityStatus");
      if (typeof status?.reason === "string") lastReason = status.reason;
    } catch (error) {
      lastReason = error instanceof Error ? error.message : String(error);
    }
  }
  throw new Error(`Transcript unavailable: ${lastReason}`);
}

export async function getCaptions(env: Env, videoId: string): Promise<CaptionBundle> {
  await ensureCaptionTable(env);
  const cached = await env.DB.prepare(
    "SELECT language, plain_text, srt_text FROM captions WHERE video_id = ?",
  ).bind(videoId).first<CaptionRow>();
  if (cached) {
    return { language: cached.language, plainText: cached.plain_text, srtText: cached.srt_text };
  }
  let captions: CaptionBundle | null = null;
  let lastError: unknown;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      captions = await fetchCaptionsFromYouTube(videoId);
      break;
    } catch (error) {
      lastError = error;
      if (attempt < 3) await sleep(250 * attempt);
    }
  }
  if (!captions) throw lastError instanceof Error ? lastError : new Error("Transcript unavailable.");
  const byteLength = new TextEncoder().encode(captions.plainText + captions.srtText).byteLength;
  if (byteLength <= MAX_CACHED_CAPTION_BYTES) {
    await env.DB.prepare(
      `INSERT OR REPLACE INTO captions (video_id, language, plain_text, srt_text, fetched_at)
       VALUES (?, ?, ?, ?, ?)`,
    ).bind(videoId, captions.language, captions.plainText, captions.srtText, new Date().toISOString()).run();
  }
  return captions;
}

