async function resolveYouTubeChannel(input: string): Promise<{ channelId: string; channelName: string; videos: Video[] }> {
  const normalized = normalizeYouTubeInput(input);
  let channelId = extractChannelId(normalized);
  if (!channelId) {
    const response = await fetchWithTimeout(normalized, { redirect: "follow" });
    if (!response.ok) throw new Error(`YouTube page returned ${response.status}`);
    const body = await response.text();
    if (body.length > 5_000_000) throw new Error("YouTube page exceeded the safe response limit");
    channelId = extractChannelId(normalized, body);
  }
  if (!channelId) throw new Error("Could not resolve the creator for that YouTube address");
  const videos = await fetchFeed(channelId);
  return { channelId, channelName: videos[0]?.channelName || channelId, videos };
}

