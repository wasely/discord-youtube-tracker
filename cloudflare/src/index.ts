// Threads started from a message reuse that message's ID, so an existing
// transcript thread is found by looking the message ID up as a channel.
async function transcriptThreadId(
  env: Env,
  interaction: DiscordInteraction,
  title: string,
): Promise<string | null> {
  const channelId = interaction.channel_id;
  const messageId = interaction.message?.id;
  if (!channelId || !messageId) return null;
  try {
    const existing = await (await discordApi(env, `/channels/${messageId}`)).json() as { id?: string; type?: number };
    if (existing?.id && (existing.type === 11 || existing.type === 12)) return String(existing.id);
  } catch {
    // No thread exists for this message yet.
  }
  try {
    const created = await (await discordApi(env, `/channels/${channelId}/messages/${messageId}/threads`, {
      method: "POST",
      body: JSON.stringify({
        name: `Transcript — ${title}`.replace(/\s+/g, " ").slice(0, 95),
        auto_archive_duration: 1440,
      }),
    })).json() as { id?: string };
    return created?.id ? String(created.id) : null;
  } catch (error) {
    logEvent("warn", "transcript_thread_unavailable", {
      channel_id: channelId,
      error: error instanceof Error ? error.message : String(error),
    });
    return null;
  }
}

export function transcriptChatChunks(
  captions: CaptionBundle,
  metadata: VideoMetadata,
  transcriptUrl: string,
): string[] {
  const body = splitDiscordText(captions.plainText.replace(/\n{2,}/g, "\n").trim(), 1_900);
  const truncated = body.length > CHAT_TRANSCRIPT_MAX_MESSAGES;
  const chunks = truncated ? body.slice(0, CHAT_TRANSCRIPT_MAX_MESSAGES) : body;
  const header = `**${metadata.title.replace(/[*_`]/g, "").slice(0, 200)}** — full transcript (${metadata.channelName})`;
  chunks[0] = `${header}\n\n${chunks[0]}`.slice(0, 1_990);
  if (truncated && transcriptUrl) {
    chunks.push(`Transcript continues. Read or copy the rest here: ${transcriptUrl}`);
  }
  return chunks;
}

export async function sendChatTranscript(
  env: Env,
  interaction: DiscordInteraction,
  videoId: string,
  origin: string,
): Promise<void> {
  try {
    const [captions, metadata] = await Promise.all([
      getCaptions(env, videoId),
      metadataForVideo(env, interaction, videoId),
    ]);
    const transcriptUrl = origin ? `${origin}${TRANSCRIPT_PATH_PREFIX}${videoId}` : "";
    const chunks = transcriptChatChunks(captions, metadata, transcriptUrl);
    const threadId = await transcriptThreadId(env, interaction, metadata.title);
    if (!threadId) {
      for (const chunk of chunks) await followUpInteraction(env, interaction, chunk);
      await editInteraction(env, interaction, "Transcript posted here privately.");
      return;
    }
    for (const [index, chunk] of chunks.entries()) {
      await discordApi(env, `/channels/${threadId}/messages`, {
        method: "POST",
        body: JSON.stringify({ content: chunk, allowed_mentions: { parse: [] } }),
      });
      // A long transcript is many messages into one channel, so the run is
      // paced rather than left to burn retries on 429s.
      if (index < chunks.length - 1) await sleep(CHAT_TRANSCRIPT_SPACING_MS);
    }
    await editInteraction(env, interaction, `Full transcript posted in <#${threadId}>.`);
  } catch (error) {
    await editInteraction(env, interaction, discordText(
      `Could not post this transcript. ${error instanceof Error ? error.message : String(error)}`,
    ));
  }
}

function toHex(bytes: ArrayBuffer): string {
  return [...new Uint8Array(bytes)]
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");
}

async function validCaptionCacheSignature(
  request: Request,
  body: string,
  secret: string,
): Promise<boolean> {
  const timestamp = request.headers.get("x-caption-timestamp");
  const supplied = request.headers.get("x-caption-signature")?.toLowerCase();
  if (!timestamp || !supplied || !/^[0-9a-f]{64}$/.test(supplied)) return false;
  const timestampMs = Number(timestamp) * 1000;
  if (!Number.isFinite(timestampMs) || Math.abs(Date.now() - timestampMs) > 5 * 60 * 1000) return false;
  const key = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const expected = toHex(await crypto.subtle.sign(
    "HMAC",
    key,
    new TextEncoder().encode(`${timestamp}.${body}`),
  ));
  let different = expected.length ^ supplied.length;
  for (let index = 0; index < expected.length; index += 1) {
    different |= expected.charCodeAt(index) ^ (supplied.charCodeAt(index) || 0);
  }
  return different === 0;
}

function isCaptionUpload(value: unknown): value is CaptionUpload {
  if (!value || typeof value !== "object") return false;
  const upload = value as Record<string, unknown>;
  return typeof upload.videoId === "string" && /^[A-Za-z0-9_-]{11}$/.test(upload.videoId)
    && typeof upload.language === "string" && upload.language.length > 0 && upload.language.length <= 64
    && typeof upload.plainText === "string" && upload.plainText.length > 0
    && typeof upload.srtText === "string" && upload.srtText.length > 0
    && (upload.title === undefined || (typeof upload.title === "string" && upload.title.length <= 500))
    && (upload.channelName === undefined || (typeof upload.channelName === "string" && upload.channelName.length <= 500));
}

