export function staleCardVideoId(message: {
  author?: { id?: string; bot?: boolean };
  embeds?: Array<{ url?: string }>;
  components?: Array<{ components?: Array<{ custom_id?: string }> }>;
}, applicationId: string): string | null {
  if (!message.author?.bot || String(message.author.id || "") !== applicationId) return null;
  if (hasCurrentVideoActions(message)) return null;
  const videoId = extractVideoId(message.embeds?.[0]?.url || "");
  if (videoId) return videoId;
  // Older cards can carry the video only on their buttons.
  for (const row of message.components ?? []) {
    for (const component of row.components ?? []) {
      const fromButton = parseCaptionCustomId(component.custom_id)
        || parseSummaryCustomId(component.custom_id);
      if (fromButton) return fromButton;
    }
  }
  return null;
}

// The tracker ran for months before these buttons existed, and a second
// deployment may still be posting old cards, so every card the bot owns is
// rewritten to the current action row in rotating background passes.
export async function upgradeVideoCards(env: Env, origin: string): Promise<number> {
  if (!env.DISCORD_APPLICATION_ID) return 0;
  await ensureCardUpgradeTable(env);
  const now = new Date().toISOString();
  const routes = await env.DB.prepare(
    "SELECT DISTINCT discord_channel_id FROM routes WHERE enabled = 1",
  ).all<{ discord_channel_id: string }>();
  const channelIds = new Set(routes.results.map((route) => route.discord_channel_id));
  if (!channelIds.size) {
    // Before this Worker owns the routes, the feed channels are still
    // discoverable from the category the tracker creates.
    for (const channelId of await feedCategoryChannels(env)) channelIds.add(channelId);
  }
  if (channelIds.size) {
    await env.DB.batch([...channelIds].map((channelId) => env.DB.prepare(
      "INSERT OR IGNORE INTO card_upgrade_state (discord_channel_id, before_message_id, scanned_at) VALUES (?, NULL, NULL)",
    ).bind(channelId)));
  }
  const due = await env.DB.prepare(
    `SELECT discord_channel_id, before_message_id FROM card_upgrade_state
     ORDER BY scanned_at IS NOT NULL, scanned_at LIMIT ?`,
  ).bind(CARD_UPGRADE_CHANNELS_PER_RUN).all<{ discord_channel_id: string; before_message_id: string | null }>();

  let patched = 0;
  for (const channel of due.results) {
    const result = await upgradeChannelCards(
      env,
      channel.discord_channel_id,
      origin,
      channel.before_message_id,
      CARD_UPGRADE_PATCHES_PER_CHANNEL,
    );
    patched += result.patched;
    await env.DB.prepare(
      "UPDATE card_upgrade_state SET before_message_id = ?, scanned_at = ? WHERE discord_channel_id = ?",
    ).bind(result.oldest, now, channel.discord_channel_id).run();
  }
  if (patched) logEvent("info", "cards_upgraded", { patched });
  return patched;
}

// Discord allows only a few edits per hour to messages older than an hour
// (error 30046), so a channel that hits the quota keeps its cursor and is
// picked up again on a later pass instead of skipping unrepaired cards.
function editQuotaReached(error: unknown): boolean {
  return error instanceof Error && error.message.includes("30046");
}

export async function upgradeChannelCards(
  env: Env,
  channelId: string,
  origin: string,
  before: string | null,
  maxPatches: number,
): Promise<{ patched: number; scanned: number; oldest: string | null; quotaReached: boolean }> {
  let patched = 0;
  let scanned = 0;
  let quotaReached = false;
  let cursor = before;
  try {
    const query = cursor
      ? `?limit=${CARD_UPGRADE_PAGE_SIZE}&before=${cursor}`
      : `?limit=${CARD_UPGRADE_PAGE_SIZE}`;
    const messages = await (await discordApi(env, `/channels/${channelId}/messages${query}`)).json() as Array<{
      id: string;
      author?: { id?: string; bot?: boolean };
      embeds?: Array<{ url?: string }>;
      components?: Array<{ components?: Array<{ custom_id?: string }> }>;
    }>;
    scanned = messages.length;
    cursor = messages.length === CARD_UPGRADE_PAGE_SIZE ? messages[messages.length - 1].id : null;
    for (const message of messages) {
      if (patched >= maxPatches) break;
      const videoId = staleCardVideoId(message, env.DISCORD_APPLICATION_ID);
      if (!videoId) continue;
      try {
        await discordApi(env, `/channels/${channelId}/messages/${message.id}`, {
          method: "PATCH",
          body: JSON.stringify({ components: videoActionComponents(videoId, origin) }),
        });
        patched += 1;
        // Message edits share the channel send bucket, so the sweep is paced
        // instead of burning retries on 429s.
        await sleep(CARD_UPGRADE_PATCH_SPACING_MS);
      } catch (error) {
        if (editQuotaReached(error)) {
          quotaReached = true;
          cursor = before;
          break;
        }
        logEvent("warn", "card_upgrade_message_failed", {
          discord_channel_id: channelId,
          discord_message_id: message.id,
          error: error instanceof Error ? error.message : String(error),
        });
      }
    }
  } catch (error) {
    logEvent("warn", "card_upgrade_failed", {
      discord_channel_id: channelId,
      error: error instanceof Error ? error.message : String(error),
    });
    cursor = before;
  }
  return { patched, scanned, oldest: cursor, quotaReached };
}

export async function runPoll(env: Env): Promise<number> {
  const channels = await env.DB.prepare(
    "SELECT DISTINCT youtube_channel_id FROM routes WHERE enabled = 1 ORDER BY youtube_channel_id",
  ).all<{ youtube_channel_id: string }>();
  if (!channels.results.length) return 0;
  const state = await env.DB.prepare("SELECT cursor FROM poll_state WHERE id = 1").first<{ cursor: number }>();
  const start = (state?.cursor ?? 0) % channels.results.length;
  const batch = Array.from({ length: Math.min(POLL_BATCH_SIZE, channels.results.length) }, (_, offset) =>
    channels.results[(start + offset) % channels.results.length].youtube_channel_id,
  );
  const placeholders = batch.map(() => "?").join(",");
  const routes = await env.DB.prepare(
    `SELECT * FROM routes WHERE enabled = 1 AND youtube_channel_id IN (${placeholders})`,
  ).bind(...batch).all<Route>();
  const videosByChannel = new Map<string, Video[]>();
  for (let index = 0; index < batch.length; index += 5) {
    await Promise.all(batch.slice(index, index + 5).map(async (channelId) => {
      try {
        videosByChannel.set(channelId, (await fetchFeed(channelId)).slice(0, 5));
      } catch (error) {
        console.error("YouTube feed error", error);
      }
    }));
  }
  await queueVideos(env, routes.results, videosByChannel);
  await env.DB.prepare("UPDATE poll_state SET cursor = ? WHERE id = 1")
    .bind((start + batch.length) % channels.results.length).run();
  return sendPending(env);
}

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContextLike): Promise<Response> {
    const url = new URL(request.url);
    const captionStatusRoute = url.pathname.match(/^\/caption-cache\/([A-Za-z0-9_-]{11})\/?$/);
    if (captionStatusRoute) {
      if (request.method !== "HEAD") return new Response("Method not allowed", { status: 405 });
      return captionCacheStatusResponse(request, env, captionStatusRoute[1]);
    }
    if (url.pathname === "/caption-cache") {
      if (request.method !== "POST") return new Response("Method not allowed", { status: 405 });
      return saveCaptionUpload(request, env);
    }
    const smokeRoute = url.pathname.match(/^\/admin\/smoke\/([A-Za-z0-9_-]{11})\/?$/);
    if (smokeRoute) {
      if (request.method !== "POST") return new Response("Method not allowed", { status: 405 });
      if (request.headers.get("authorization") !== `Bot ${env.DISCORD_TOKEN}`) {
        return new Response("Unauthorized", { status: 401 });
      }
      const videoId = smokeRoute[1];
      const interaction: DiscordInteraction = {
        id: `smoke-${videoId}`,
        application_id: env.DISCORD_APPLICATION_ID,
        token: "smoke",
        type: 2,
        message: { embeds: [] },
      };
      try {
        const captions = await getCaptions(env, videoId);
        const summary = await videoSummary(env, interaction, videoId);
        const [row] = videoActionComponents(videoId, publicOrigin(env, url.origin)) as Array<{
          components?: Array<{ label?: string }>;
        }>;
        return json({
          ok: true,
          videoId,
          transcriptCharacters: captions.plainText.length,
          summaryCharacters: summary.length,
          actions: row.components?.map((component) => component.label) ?? [],
        });
      } catch (error) {
        return json({ ok: false, videoId, error: error instanceof Error ? error.message : String(error) }, 503);
      }
    }
    if (url.pathname === "/admin/upgrade-cards") {
      if (request.method !== "POST") return new Response("Method not allowed", { status: 405 });
      if (request.headers.get("authorization") !== `Bot ${env.DISCORD_TOKEN}`) {
        return new Response("Unauthorized", { status: 401 });
      }
      const origin = publicOrigin(env, url.origin);
      const channelId = url.searchParams.get("channel");
      if (!channelId) return json({ ok: true, patched: await upgradeVideoCards(env, origin) });
      if (!/^\d{5,25}$/.test(channelId)) return json({ ok: false, error: "Invalid channel id" }, 400);
      const before = url.searchParams.get("before");
      const result = await upgradeChannelCards(env, channelId, origin, before, 40);
      return json({ ok: true, ...result });
    }
    if (url.pathname === "/admin/run") {
      if (request.method !== "POST") return new Response("Method not allowed", { status: 405 });
      if (request.headers.get("authorization") !== `Bot ${env.DISCORD_TOKEN}`) {
        return new Response("Unauthorized", { status: 401 });
      }
      const [posted, transcripts, summaries] = await Promise.all([
        runPoll(env),
        runTranscriptIntake(env),
        runSummaryIntake(env),
      ]);
      return json({ ok: true, posted, transcripts, summaries });
    }
    if (request.method === "GET") {
      const transcriptRoute = url.pathname.match(/^\/transcript\/([A-Za-z0-9_-]{11})(?:\/(plain))?\/?$/);
      if (transcriptRoute) return transcriptPageResponse(env, transcriptRoute[1], transcriptRoute[2] === "plain");
      const copyRoute = url.pathname.match(/^\/copy\/([A-Za-z0-9_-]{11})\/?$/);
      if (copyRoute) return copyPageResponse(env, copyRoute[1]);
      if (url.pathname === "/health") {
        try {
          await env.DB.prepare("SELECT 1").first();
          let fastIntake: unknown = "not configured";
          if (env.FAST_INTAKE) {
            const id = env.FAST_INTAKE.idFromName("primary");
            fastIntake = await (await env.FAST_INTAKE.get(id).fetch("https://fast-intake/status")).json();
          }
          return json({ status: "ok", service: PRODUCT_NAME, version: DEPLOYMENT_VERSION, database: "ok", fastIntake });
        } catch {
          return json({ status: "degraded", service: PRODUCT_NAME, version: DEPLOYMENT_VERSION, database: "unavailable" }, 503);
        }
      }
      return new Response(`${PRODUCT_NAME} is running.`);
    }
    if (request.method !== "POST") return new Response("Method not allowed", { status: 405 });
    const body = await request.arrayBuffer();
    if (!(await verifyDiscordRequest(request, env.DISCORD_PUBLIC_KEY, body))) return new Response("Invalid signature", { status: 401 });
    const interaction = JSON.parse(new TextDecoder().decode(body)) as DiscordInteraction;
    if (interaction.type === 1) return json({ type: 1 });
    if (interaction.type === 3) {
      const origin = publicOrigin(env, url.origin);
      const copyLinkVideoId = parseCopyLinkCustomId(interaction.data?.custom_id);
      if (copyLinkVideoId) return json(copyLinkResponse(copyLinkVideoId, origin));
      const chatTranscriptVideoId = parseChatTranscriptCustomId(interaction.data?.custom_id);
      if (chatTranscriptVideoId) {
        ctx.waitUntil(sendChatTranscript(env, interaction, chatTranscriptVideoId, origin));
        return json({ type: 5, data: { flags: 64 } });
      }
      const captionVideoId = parseCaptionCustomId(interaction.data?.custom_id);
      if (captionVideoId) {
        ctx.waitUntil(sendCaptionDownload(env, interaction, captionVideoId, url.origin));
        return json({ type: 5, data: { flags: 64 } });
      }
      const summaryVideoId = parseSummaryCustomId(interaction.data?.custom_id);
      if (summaryVideoId) {
        ctx.waitUntil(sendVideoSummary(env, interaction, summaryVideoId));
        return json({ type: 5, data: { flags: 64 } });
      }
      const questionVideoId = parseSummaryQuestionCustomId(interaction.data?.custom_id);
      if (questionVideoId) return json(summaryQuestionModal(questionVideoId));
      return json({ type: 4, data: { content: "Unknown video action.", flags: 64 } });
    }
    if (interaction.type === 5) {
      const videoId = parseSummaryAnswerModalId(interaction.data?.custom_id);
      if (!videoId) return json({ type: 4, data: { content: "Unknown summary question.", flags: 64 } });
      ctx.waitUntil(sendSummaryAnswer(env, interaction, videoId));
      return json({ type: 5, data: { flags: 64 } });
    }
    if (interaction.type !== 2) return json({ type: 4, data: { content: "Unsupported interaction.", flags: 64 } });
    ctx.waitUntil(handleInteraction(env, interaction));
    return json({ type: 5, data: { flags: 64 } });
  },

  async scheduled(event: ScheduledEvent, env: Env, ctx: ExecutionContextLike): Promise<void> {
    // Card repair runs on its own trigger so it never competes with polling
    // for one invocation's subrequest budget.
    if (event.cron === CARD_UPGRADE_CRON) {
      ctx.waitUntil(upgradeVideoCards(env, publicOrigin(env, ""))
        .then((patched) => console.log(`Card upgrade: ${patched} message(s)`))
        .catch((error) => logEvent("warn", "card_upgrade_pass_failed", {
          error: error instanceof Error ? error.message : String(error),
        })));
      return;
    }
    ctx.waitUntil(ensureFastIntake(env));
    ctx.waitUntil(Promise.all([
      runPoll(env).then((posted) => console.log(`Poll complete: ${posted} new video(s)`)),
    ]).then(() => undefined));
  },
};
